import os
from typing import Any, Dict, List
from groq import Groq

SYSTEM_PROMPT = """You are a Senior Telecom Retention Analyst.
Your task is to analyze churn risk using SHAP factor contributions and the customer's profile (especially tenure, contract, and subscribed services).

Structure your response strictly into two sections:
### 🔍 Risk Diagnosis (SHAP & Profile)
Provide a 2-3 sentence diagnosis explaining WHY this customer is at risk, connecting the top SHAP drivers with their tenure and service profile.

### 🎯 Retention Recommendations
Provide 2-3 concrete, realistic business actions directly targeting the identified drivers:
- **[Action 1 - Primary SHAP Risk]**: Specific offer or plan change to neutralize the biggest risk.
- **[Action 2 - Secondary Gap/Service]**: Proposal addressing missing services (e.g., Tech Support, Security) or contract terms.
- **[Action 3 - Tenure & Relationship Lever]**: Action tailored to their customer stage (e.g., onboarding discount for new users, loyalty credit for long-tenure customers).

Keep it professional, highly specific, and actionable."""


def _categorize_tenure(tenure: int) -> str:
    if tenure <= 3:
        return f"{tenure} month(s) (New customer / High onboarding drop-off risk)"
    elif tenure <= 12:
        return f"{tenure} month(s) (First-year customer)"
    elif tenure <= 36:
        return f"{tenure} month(s) (Mid-term established customer)"
    return f"{tenure} month(s) (Long-term / High-LTV loyal customer)"


def _build_user_message(
    churn_prob: float,
    customer_profile: Dict[str, Any],
    top_risks: List[Dict[str, Any]],
    top_protections: List[Dict[str, Any]],
) -> str:
    tenure_months = int(customer_profile.get("tenure", 0))
    tenure_desc = _categorize_tenure(tenure_months)

    security = customer_profile.get("OnlineSecurity", "No")
    tech_support = customer_profile.get("TechSupport", "No")
    backup = customer_profile.get("OnlineBackup", "No")
    internet = customer_profile.get("InternetService", "None")

    risks_str = (
        "\n".join([f"  • {item['feature']}: impact +{item['impact']:.3f}" for item in top_risks])
        if top_risks else "  • None identified"
    )
    protections_str = (
        "\n".join([f"  • {item['feature']}: impact {item['impact']:.3f}" for item in top_protections])
        if top_protections else "  • None identified"
    )

    return f"""Customer Context:
- Tenure / Stage: {tenure_desc}
- Contract Type: {customer_profile.get('Contract', 'N/A')}
- Internet Service: {internet}
- Monthly Charges: ${customer_profile.get('MonthlyCharges', 'N/A')} (Total Spent: ${customer_profile.get('TotalCharges', 'N/A')})
- Payment Method: {customer_profile.get('PaymentMethod', 'N/A')}
- Value-Added Services: Online Security={security}, Tech Support={tech_support}, Backup={backup}

Model Risk Assessment:
- Churn Probability: {churn_prob * 100:.2f}%

Local SHAP Contributors:
Top Risk Drivers (Pushing towards churn):
{risks_str}

Top Retention Factors (Holding customer):
{protections_str}

Analyze the customer situation and output the diagnosis and retention recommendations."""


def generate_retention_plan(
    churn_prob: float,
    customer_profile: Dict[str, Any],
    top_risks: List[Dict[str, Any]],
    top_protections: List[Dict[str, Any]],
) -> str:
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        return "⚠️ **GROQ_API_KEY** is not configured in `.env`."

    model = os.getenv("GROQ_MODEL", "qwen/qwen3.8-27b")

    user_message = _build_user_message(
        churn_prob=churn_prob,
        customer_profile=customer_profile,
        top_risks=top_risks,
        top_protections=top_protections,
    )

    try:
        client = Groq(api_key=api_key)
        response = client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_message},
            ],
            temperature=0.2,
            max_tokens=800,
        )

        content = response.choices[0].message.content
        if not content:
            return "⚠️ No response generated by the agent."

        return content.strip()

    except Exception as exc:
        return f"⚠️ Error generating retention plan: {str(exc)}"